/**
 * Context-Aware Islamic Content Sanitizer for Roayti backend.
 * Filters out polytheistic expressions (shirk), false divinity claims,
 * and fantasy god tropes, smoothly transforming them into rich, majestic,
 * and contextually appropriate Arabic literary expressions.
 */

export function containsShirkOrProhibited(text: string): boolean {
  if (!text || typeof text !== 'string') return false;

  const shirkPatterns = [
    /(?:^|[\s([«،؛:.\-'"“‘])(?:إله|اله|إلهة|الهة)\s+(ال[^\s.,!؟،؛)]+)/u,
    /(?:^|[\s([«،؛:.\-'"“‘])(?:ال)?(?:آلهة|الهة|ألهة)/u,
    /نصف\s+(?:إله|اله)/u,
    /أنصاف\s+(?:ال)?(?:آلهة|الهة|ألهة)/u,
    /شبه\s+(?:إله|اله)/u,
    /(?:تأليه|التأليه|ألوهية|الألوهية)/u,
    /أصبح\s+(?:إلهاً|الهاً|إله|اله)/u,
    /(?:أنا|أنه|هو)\s+(?:إلهكم|الهكم|إله|اله|الإله|الاله)/u,
    /بحق\s+(?:ال)?(?:آلهة|الهة|ألهة)/u,
    /أقسم\s+ب(?:ال)?(?:آلهة|الهة|ألهة)/u,
    /(?:سجد|يسجد|خر|سجود)\s+.*?(?:كإله|كالآلهة)/u,
    /\bgod of\b/i,
    /\bgoddess of\b/i,
    /\bthe gods\b/i,
    /\bdemigods?\b/i,
  ];

  return shirkPatterns.some(pattern => pattern.test(text));
}

export function sanitizeIslamicContent(text: string): string {
  if (!text || typeof text !== 'string') return text;
  let res = text;

  // 1. Dialogue oaths and exclamations (سياق القسم والحوارات والتعجب)
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))بحق\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'بحق السماء');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))أقسم\s+ب(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'أقسم بشرفي');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))(?:أيتها|ايتها)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'يا للهول');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))يا\s+ل(?:لآلهة|لالهة)/gu, 'يا للعجب');
  res = res.replace(/(?:فلتباركك|لتباركك|باركتك)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'حفظتك العناية وحالفك التوفيق');
  res = res.replace(/لعنتك\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'حلت عليك اللعنة');
  res = res.replace(/استغفر\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'تراجع عن حماقتك');
  res = res.replace(/(?:صلوات|ابتهالات)\s+ل(?:لآلهة|لالهة)/gu, 'ابتهالات للسماء');
  res = res.replace(/(?:قربان|قرابين)\s+ل(?:لآلهة|لالهة)/gu, 'قرابين لصرح الأسلاف');

  // 2. Specific mythological / fantasy titles (سياق القوى والعناصر والمعارك)
  const contextualTitles = [
    // الرعد والبرق
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الرعد|الصواعق|البرق)/gu, replace: '$1سيد $2' },
    // الحرب والقتال والمعارك
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الحرب)/gu, replace: '$1أمير الحرب' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(المعركة|القتال|النزال)/gu, replace: '$1سيد $2' },
    // الموت والفناء
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الموت)/gu, replace: '$1حاصد الأرواح' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الفناء|الهلاك)/gu, replace: '$1سيد $2' },
    // النار والحرارة
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(النار|اللهب|الجحيم|النيران)/gu, replace: '$1سيد $2' },
    // الرياح والعواصف
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الرياح)/gu, replace: '$1سلطان الرياح' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(العواصف)/gu, replace: '$1عاهل العواصف' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الأعاصير)/gu, replace: '$1سيد الأعاصير' },
    // البحر والماء
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(البحر|المحيط|الأعماق|المياه|البحار)/gu, replace: '$1سيد الأعماق' },
    // الشمس والنور
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الشمس|النهار|الضياء)/gu, replace: '$1عاهل الضياء' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(النور|الضوء)/gu, replace: '$1سيد النور' },
    // القمر والظلام
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(القمر)/gu, replace: '$1سيد النور الفضي' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الليل|الظلام|العتمة|الظلمات)/gu, replace: '$1سيد الظلمات' },
    // الدمار والشر والفوضى
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الدمار|الفوضى|الخراب|الشر|الخبث)/gu, replace: '$1طاغية $2' },
    // السيوف والنصال
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(السيف|النصل|السيوف|النصال)/gu, replace: '$1سيد النصال' },
    // الحكمة والصيد والطباعة
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الحكمة|المعرفة)/gu, replace: '$1سيد الحكمة' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(الصيد|القنص)/gu, replace: '$1سيد القنص' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(القدر|المصير|الزمان)/gu, replace: '$1متحكم $2' },

    // المؤنث (إلهة)
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إلهة|الهة)\s+(القمر)/gu, replace: '$1سيدة القمر' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إلهة|الهة)\s+(الجمال|الحسن)/gu, replace: '$1أميرة الحسن' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إلهة|الهة)\s+(الحرب)/gu, replace: '$1سيدة المعارك' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إلهة|الهة)\s+(الحكمة)/gu, replace: '$1سيدة الحكمة' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إلهة|الهة)\s+(الصيد)/gu, replace: '$1أميرة القنص' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إلهة|الهة)\s+(الموت|الفناء)/gu, replace: '$1سيدة الفناء' },
    { pattern: /(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إلهة|الهة)\s+(النور|الضياء)/gu, replace: '$1سيدة النور' },
  ];

  for (const { pattern, replace } of contextualTitles) {
    res = res.replace(pattern, (match, prefix, noun) => (prefix || '') + replace.replace('$1', '').replace('$2', noun));
  }

  // 3. General Idafa for other "إله [الـ...]" and "إلهة [الـ...]"
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إله|اله)\s+(ال[^\s.,!؟،؛)]+)/gu, (match, prefix, noun) => {
    return (prefix || '') + 'سيد ' + noun;
  });
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)?(?:إلهة|الهة)\s+(ال[^\s.,!؟،؛)]+)/gu, (match, prefix, noun) => {
    return (prefix || '') + 'سيدة ' + noun;
  });

  // 4. Demigods / Offspring (أنصاف آلهة وسلالات)
  res = res.replace(/نصف\s+(?:إله|اله)/gu, 'نصف جبار');
  res = res.replace(/أنصاف\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'أنصاف جبابرة');
  res = res.replace(/شبه\s+(?:إله|اله)/gu, 'شبه جبار');
  res = res.replace(/(?:ابن|أبناء|نسل|سلالة|دم)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, (m) => {
    if (m.startsWith('ابن')) return 'ابن الجبابرة';
    if (m.startsWith('أبناء')) return 'أبناء الجبابرة';
    if (m.startsWith('نسل')) return 'نسل الجبابرة الأساطير';
    if (m.startsWith('سلالة')) return 'سلالة الأساطير العظمى';
    return 'جوهر الأساطير العظيم';
  });

  // 5. Mythological realms, eras, weapons, and assemblies (سياق العالم والأسطورة)
  res = res.replace(/(?:ال)?(?:آلهة|الهة|ألهة)\s+القديمة/gu, 'الجبابرة القدامى');
  res = res.replace(/(?:ال)?(?:آلهة|الهة|ألهة)\s+العليا/gu, 'الكيانات العليا');
  res = res.replace(/(?:ال)?(?:آلهة|الهة|ألهة)\s+السبعة/gu, 'الجبابرة السبعة');
  res = res.replace(/(?:ال)?(?:آلهة|الهة|ألهة)\s+(?:الإثني|الاثني|الاثنا|الإثنا)\s+عشر/gu, 'الجبابرة الاثنا عشر');
  res = res.replace(/مجلس\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'مجلس الجبابرة الأكبر');
  res = res.replace(/(?:عصر|زمن|عهد)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'عصر الأساطير');
  res = res.replace(/(?:معبد|صرح|محراب)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'صرح الأساطير');
  res = res.replace(/(?:عالم|أرض|مملكة|مدينة|حاضرة)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'عالم الأساطير');
  res = res.replace(/عرش\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'عرش الجبابرة');
  res = res.replace(/(?:مقبرة|قبر)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'مقبرة الجبابرة');
  res = res.replace(/(?:غضب|لعنة)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'غضب الجبابرة');
  res = res.replace(/(?:حرب|معركة)\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'حرب الجبابرة العظمى');
  res = res.replace(/سلاح\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'سلاح الأساطير الخارق');
  res = res.replace(/قوة\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'قوة الجبابرة الخارقة');
  res = res.replace(/بركة\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'بركة الأسلاف وتوفيق المسعى');

  // 6. False divinity claims & tyrants (ادعاء الألوهية)
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))(?:أنا|أنه|هو)\s+(?:إلهكم|الهكم)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'أنا سيدكم المطلق');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))(?:أنا|أنه|هو)\s+(?:إله|اله|الإله|الاله)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'أنا السيد الأقوى والأعظم');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))(?:إلههم|الههم|آلهتهم|الهتهم)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'أسيادهم القدامى');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))(?:إلهنا|الهنا|آلهتنا|الهتنا)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'قادتنا العظماء');

  // 7. Worship / Prostration to creatures (سياق الخضوع والتعظيم)
  res = res.replace(/(?:سجدوا|يسجدون|خروا|انحنوا)\s+(?:له\s+)?ك(?:إله|اله|الآلهة)/gu, 'انحنوا له إجلالاً كقائد مطلق');
  res = res.replace(/(?:عبدوه|يعبدونه|قدسوه)\s+(?:كإله|كالآلهة)/gu, 'بجلوه وانقادوا لسطوته كأعظم قائد');

  // 8. Standalone plural "الآلهة" & "آلهة"
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)ال(?:آلهة|الهة|ألهة)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, (m, p) => (p || '') + 'الجبابرة');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))([وفلكب]?)(?:آلهة|الهة|ألهة)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, (m, p) => (p || '') + 'جبابرة');

  // 9. Comparisons & apotheosis (التأليه وبلوغ القوة القصوى)
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))ك(?:إله|اله)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'كسيد عظيم وجبار أسطوري');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))ك(?:إلهة|الهة)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'كسيدة عظيمة');
  res = res.replace(/أصبح\s+(?:إلهاً|الهاً|إله|اله)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'أصبح جباراً أسطورياً لا يُقهر');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))(?:تأليه|التأليه)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'الارتقاء الأسطوري');
  res = res.replace(/(?:^|(?<=[\s([«،؛:.\-'"“‘]))(?:ألوهية|الألوهية)(?=$|[\s)».,!؟،؛:\-'"”’])/gu, 'الجبروت الأسطوري');
  res = res.replace(/تضاهي\s+(?:ال)?(?:آلهة|الهة|ألهة)/gu, 'تضاهي الجبابرة الأوائل');

  // 10. English fantasy equivalents
  res = res.replace(/\bgod of thunder\b/gi, 'Lord of Thunder');
  res = res.replace(/\bgod of war\b/gi, 'Warlord Supreme');
  res = res.replace(/\bgod of death\b/gi, 'Reaper of Souls');
  res = res.replace(/\bgod of fire\b/gi, 'Lord of Fire');
  res = res.replace(/\bgod of (the )?([a-z]+)\b/gi, (m, the, noun) => `Lord of ${the || ''}${noun}`);
  res = res.replace(/\bgoddess of (the )?([a-z]+)\b/gi, (m, the, noun) => `Lady of ${the || ''}${noun}`);
  res = res.replace(/\bthe gods\b/gi, 'the ancient titans');
  res = res.replace(/\bdemigods?\b/gi, (m) => m.toLowerCase().endsWith('s') ? 'legendary champions' : 'legendary champion');

  return res;
}
